    /**
     * A **signal**, not a datum: it re-emits every time the catalogue changes.
     *
     * The number it carries means nothing and must not be read — two different catalogues can
     * perfectly well produce the same count. What matters is that Room re-emits: a `@Query`'s
     * invalidation covers every table the query names, subqueries included, so this re-emits both
     * when a listing changes and when its versions do.
     *
     * It serves whoever computes something in Kotlin that depends on both tables — "is there an
     * update for this app?" — and therefore cannot rely on the invalidation of a query reading a
     * single table.
     */
    @Query("SELECT (SELECT COUNT(*) FROM store_listings) + (SELECT COUNT(*) FROM app_versions)")
    fun observeCatalogRevision(): Flow<Long>
